"""Static, non-executing checks for project-owned shell command examples."""

from __future__ import annotations

import json
import re
import shlex
import tomllib
from configparser import ConfigParser
from pathlib import Path

from rapidfuzz import fuzz

from docs_drift.docs.qualifiers import context_finding
from docs_drift.index.base import CodeIndex
from docs_drift.match.context import MatchContext
from docs_drift.models import Claim, Evidence, Finding, SymbolKind, Verdict
from docs_drift.safe_files import metadata_text

MIN_WRAPPER_TOKENS = 3
MIN_SUBCOMMAND_TOKENS = 3
# Help is generated by every supported CLI framework even when no source declares it.
_IMPLICIT_FLAGS = frozenset({"--help"})
# Frameworks often add these implicitly (click.version_option, argparse -h), so absence is weak evidence.
_OFTEN_IMPLICIT_FLAGS = frozenset({"-h", "--version", "-V", "-v"})
STRONG_INVALID = 0.8
WEAK_INVALID = 0.55
# Plain character similarity: typos and plurals (--line-number vs --line-numbers) score above 88.
_NEAR_MISS_RATIO = 88
# Character similarity says little about very short names such as ``-a`` or ``--td``.
_MIN_SIMILAR_CHARS = 4
_SHELL_OPERATORS = frozenset({"|", "||", "&&", ";", "&", "2>&1"})
_RUNNER_FILES = {
    "make": ("Makefile", "makefile", "GNUmakefile"),
    "just": ("justfile", "Justfile", ".justfile"),
}


def _project_bins(repo: Path) -> set[str]:
    names: set[str] = set()
    pyproject = repo / "pyproject.toml"
    try:
        data = tomllib.loads(metadata_text(pyproject))
        scripts = data.get("project", {}).get("scripts", {})
        if isinstance(scripts, dict):
            names.update(str(name) for name in scripts)
    except (OSError, tomllib.TOMLDecodeError, AttributeError):
        pass
    package = repo / "package.json"
    try:
        data = json.loads(metadata_text(package))
        bin_value = data.get("bin", {})
        if isinstance(bin_value, str) and isinstance(data.get("name"), str):
            names.add(data["name"])
        if isinstance(bin_value, dict):
            names.update(str(name) for name in bin_value)
        scripts = data.get("scripts", {})
        if isinstance(scripts, dict):
            names.update(str(name) for name in scripts)
    except (OSError, json.JSONDecodeError, AttributeError):
        pass
    setup_cfg = ConfigParser()
    try:
        setup_cfg.read_string(metadata_text(repo / "setup.cfg"))
        if setup_cfg.has_option("options.entry_points", "console_scripts"):
            names.update(
                line.split("=", 1)[0].strip()
                for line in setup_cfg.get("options.entry_points", "console_scripts").splitlines()
                if "=" in line
            )
    except (OSError, ValueError):
        pass
    return names


def _tokens(claim: Claim) -> list[str]:
    try:
        return shlex.split(claim.value, posix=True)
    except ValueError:
        return []


def _is_data(token: str) -> bool:
    """Tokens that are values or placeholders, never options: ``-`` (stdin), ``-1``, ``--[TAB]``, ``<file>``.

    A token holding whitespace was quoted in the shell (``--pip-args '--trusted-host x'``): it is
    one value, often options for another program, never an option of this one.
    """
    return (
        token == "-"
        or bool(re.fullmatch(r"-\d+(?:\.\d+)?", token))
        or any(mark in token for mark in "[<{")
        or any(char.isspace() for char in token)
    )


def _clustered(flag: str, flag_names: set[str]) -> bool:
    """Short-option forms parsers accept: ``-vv`` (repeated), ``-abc`` (combined), ``-t10m`` (glued value)."""
    if flag.startswith("--") or len(flag) <= 2:  # noqa: PLR2004 - "-x"
        return False
    return f"-{flag[1]}" in flag_names


def _unknown_tokens(  # noqa: PLR0913 - token roles plus parser metadata.
    tokens: list[str],
    command_names: set[str],
    flag_names: set[str],
    *,
    root_positional: bool = False,
    passthrough: frozenset[str] = frozenset(),
    nullary: frozenset[str] = frozenset(),
) -> list[tuple[str, bool]]:
    """Return unknown flags and subcommands, each with whether a known subcommand precedes it.

    ``passthrough`` names the subcommands whose positional argument collects every later token
    for another program (argparse ``REMAINDER``: ``pipx run APP --app-flag``). ``nullary`` names
    boolean flags, which never take the next token as their value.
    """
    resolved = False
    current: str | None = None
    arguments = False
    unknown: list[tuple[str, bool]] = []
    previous_option = False
    for token in tokens:
        # `--` and `---` (scalene) end option parsing.
        if (
            (len(token) > 1 and set(token) == {"-"})
            or token in _SHELL_OPERATORS
            or token.startswith(("$(", "`", ">", "<", "|"))
        ):
            # Later values are positional data, or belong to another command in a pipeline or subshell.
            break
        if _is_data(token):
            previous_option = False
            continue
        if token.startswith("-"):
            flag = token.split("=", 1)[0]
            if flag not in flag_names and flag not in _IMPLICIT_FLAGS and not _clustered(flag, flag_names):
                unknown.append((flag, resolved))
            previous_option = "=" not in token and flag not in nullary
        elif token in command_names and not arguments:
            resolved = True
            current = token
            previous_option = False
        elif resolved and current in passthrough and not previous_option:
            break  # The pass-through positional starts here; the rest belongs to the program it runs.
        elif not arguments:
            # Paths, numbers, option values and prose arguments are not evidence of an unknown command.
            # Without option arity metadata, abstain from interpreting an option's next value.
            if previous_option:
                previous_option = False
                continue
            # A root that declares positional arguments (`np <version>`) takes bare words as values.
            if command_names and not resolved and not root_positional and re.fullmatch(r"[a-z][a-z0-9_-]*", token):
                unknown.append((token, False))
            # The first positional argument ends the subcommand path.
            arguments = True
    return unknown


def _strength(
    token: str, resolved: bool, command_names: set[str], flag_names: set[str], *, grouped: bool
) -> tuple[bool, str | None]:
    """Whether an unknown token is strong evidence of drift, plus a close indexed name if one exists.

    ``grouped`` means the CLI has subcommands: then a root-level option may belong to a default
    command or a shared decorator the index did not attribute, so even a near miss stays weak.
    """
    names = flag_names if token.startswith("-") else command_names
    # Names differing only in edge punctuation are index or tokenization artifacts, not renames.
    core = token.strip("-_")
    short = len(core) < _MIN_SIMILAR_CHARS
    ranked = sorted(
        ((fuzz.ratio(token, name), name) for name in names if name.strip("-_") != core and not short),
        reverse=True,
    )
    near = ranked[0][1] if ranked and ranked[0][0] >= _NEAR_MISS_RATIO else None
    if near and len(ranked) > 1 and ranked[0][0] == ranked[1][0]:
        near = None
    if token in _OFTEN_IMPLICIT_FLAGS:
        return False, near
    # A flag after a resolved subcommand contradicts that subcommand's declaration. A word in
    # subcommand position, or a root-level flag, may be a positional argument, a default
    # command's input or an option the framework adds implicitly.
    scoped = resolved or not grouped
    return bool(token.startswith("-") and resolved) or bool(near and scoped), near


_ERROR_OUTPUT = re.compile(r"^\s*(?:[\w.-]+(?:\s+[\w.-]+)?:\s+)?(?:error|usage error|fatal):", re.IGNORECASE)
_PROMPT = re.compile(r"^\s*(?:\$|>>>|PS>|#)\s")
_OUTPUT_LINES = 4


def _shows_error(claim: Claim, context: MatchContext) -> bool:
    """True when the lines printed after a documented command are an error message."""
    lines = context.lines(claim.doc_path) or []
    for text in lines[claim.line : claim.line + _OUTPUT_LINES]:
        if not text.strip() or _PROMPT.match(text) or text.lstrip().startswith(("```", "~~~")):
            return False
        if _ERROR_OUTPUT.match(text):
            return True
    return False


def _runner_unreadable(wrapper: str, index: CodeIndex, context: MatchContext) -> bool:
    """True when the task-runner file exists but its targets cannot be checked statically."""
    files = [path for name in _RUNNER_FILES.get(wrapper, ()) for path in context.paths_with_basename(name)]
    if not files:
        return False
    if not any(index.by_file.get(path) for path in files):
        return True
    # A pattern rule (``%:``) accepts any target name, so absence is not evidence.
    return any(re.match(r"^%\S*\s*:", line) for path in files for line in (context.lines(path) or []))


def _comment_names_reader(claim: Claim, context: MatchContext) -> bool:
    """`npm run test # Your test script that runs vitest`: the trailing comment attributes it."""
    lines = context.lines(claim.doc_path) or []
    if not 1 <= claim.line <= len(lines):
        return False
    _, _, comment = lines[claim.line - 1].partition(" #")
    return bool(re.search(r"\byour\b", comment, re.IGNORECASE))


def _doc_defines_script(claim: Claim, name: str, context: MatchContext) -> bool:
    """True when the document shows a ``"scripts"`` entry for this name (`"test:unit": "vitest ..."`)."""
    entry = re.compile(r'^\s*"' + re.escape(name) + r'"\s*:\s*"')
    return any(entry.match(line) for line in context.lines(claim.doc_path) or [])


def runner_declares_all(text: str, index: CodeIndex, context: MatchContext) -> bool:
    """Whether the Makefile/justfile named by ``make X``/``just X`` exists and lists every target."""
    wrapper = "just" if text.lstrip().startswith("just") else "make"
    files = [path for name in _RUNNER_FILES[wrapper] for path in context.paths_with_basename(name)]
    return bool(files) and not _runner_unreadable(wrapper, index, context)


def _unverifiable(claim: Claim, evidence: list[Evidence], reason: str, confidence: float = 0.2) -> Finding:
    return Finding(
        claim=claim, verdict=Verdict.unverifiable, evidence=evidence, confidence=confidence, reasons=[reason]
    )


def _validate_target(claim: Claim, tokens: list[str], index: CodeIndex, context: MatchContext) -> Finding:
    base_evidence = [Evidence(file=claim.doc_path, line=claim.line, text=claim.raw_text)]
    wrapper = tokens[0].casefold()
    target = next(
        (symbol for symbol in index.by_kind.get(SymbolKind.make_target, []) if symbol.name == tokens[1]), None
    )
    if target:
        return Finding(
            claim=claim,
            matched_symbol=target,
            verdict=Verdict.ok,
            evidence=[*base_evidence, Evidence(file=target.file, line=target.line, text=target.name)],
            confidence=0.9,
            reasons=[f"Project target {target.name} exists."],
        )
    if _runner_unreadable(wrapper, index, context):
        return _unverifiable(
            claim,
            base_evidence,
            f"The {wrapper} file exists, but its targets could not be read statically or a pattern rule "
            f"accepts any name, so target {tokens[1]} cannot be checked.",
            0.3,
        )
    return Finding(
        claim=claim,
        verdict=Verdict.invalid_command,
        evidence=base_evidence,
        confidence=0.85,
        reasons=[f"Project target {tokens[1]} was not found."],
    )


def validate_command(  # noqa: PLR0911, PLR0912, PLR0915 - ordered evidence checks.
    claim: Claim,
    index: CodeIndex,
    repo: Path,
    context: MatchContext | None = None,
    bins: set[str] | None = None,
) -> Finding:
    """Validate one command only when its root is independently tied to this project."""
    contextual = context_finding(claim)
    if contextual is not None:
        return contextual
    context = context or MatchContext(repo.resolve(), index)
    tokens = _tokens(claim)
    base_evidence = [Evidence(file=claim.doc_path, line=claim.line, text=claim.raw_text)]
    if not tokens:
        return _unverifiable(claim, base_evidence, "The documented command could not be tokenized safely.")
    scripts = index.by_kind.get(SymbolKind.package_script, [])
    wrapper = tokens[0].casefold()
    if wrapper in {"make", "just"} and len(tokens) > 1:
        return _validate_target(claim, tokens, index, context)
    executable_index = 0
    if wrapper in {"npm", "pnpm", "yarn"} and len(tokens) >= MIN_SUBCOMMAND_TOKENS and tokens[1] == "run":
        script = next((symbol for symbol in scripts if symbol.name == tokens[2]), None)
        if script:
            return Finding(
                claim=claim,
                matched_symbol=script,
                verdict=Verdict.ok,
                evidence=[*base_evidence, Evidence(file=script.file, line=script.line, text=script.name)],
                confidence=0.9,
                reasons=[f"Package script {script.name} exists."],
            )
        if _is_data(tokens[2]) or tokens[2].startswith("$"):
            return _unverifiable(claim, base_evidence, f"{tokens[2]} is a placeholder for a script name.")
        if not any(symbol.framework != "package-manager" for symbol in scripts):
            return _unverifiable(
                claim,
                base_evidence,
                "The package this document belongs to declares no scripts, so the command runs elsewhere.",
            )
        if _comment_names_reader(claim, context):
            return _unverifiable(claim, base_evidence, "The example's own comment says this is the reader's script.")
        if _doc_defines_script(claim, tokens[2], context):
            return _unverifiable(
                claim,
                base_evidence,
                f"The document's own package.json example defines {tokens[2]}; it runs in the reader's project.",
            )
        return Finding(
            claim=claim,
            verdict=Verdict.invalid_command,
            evidence=base_evidence,
            confidence=0.85,
            reasons=[f"Package script {tokens[2]} was not found."],
        )
    if wrapper in {"npx", "uv", "poetry", "npm", "pnpm", "yarn"} and len(tokens) >= MIN_WRAPPER_TOKENS:
        executable_index = 2
        if wrapper == "npx" and len(tokens) > 1:
            executable_index = 1
    if wrapper in {"python", "python3"} and len(tokens) >= MIN_SUBCOMMAND_TOKENS and tokens[1] == "-m":
        executable_index = 2
    executable = tokens[executable_index]
    project_path = (
        (repo / executable.removeprefix("./")).is_file() if "/" in executable or "\\" in executable else False
    )
    cli_symbols = index.by_kind.get(SymbolKind.cli_command, [])
    cli_roots = [symbol for symbol in cli_symbols if symbol.parent_id is None]
    root_matches = [symbol for symbol in cli_roots if executable == symbol.name or executable in symbol.aliases]
    known_modules = {symbol.qualified_name.split(".", 1)[0] for symbol in cli_symbols}
    module_match = executable.replace("-", "_") in known_modules
    bins = _project_bins(repo) if bins is None else bins
    belongs = executable in bins or bool(root_matches) or module_match or project_path
    if not belongs:
        return Finding(
            claim=claim,
            verdict=Verdict.unverifiable,
            evidence=base_evidence,
            confidence=0.15,
            reasons=[f"Command {executable} is not identified as a project command; third-party commands are skipped."],
        )
    script_path = executable.removeprefix("./").replace("\\", "/")
    if project_path and not root_matches and not module_match and not index.by_file.get(script_path):
        return _unverifiable(
            claim,
            base_evidence,
            f"{executable} is a repository script with no indexed CLI declaration; it forwards its arguments "
            "to another program, so they cannot be checked against this project's CLI.",
        )
    command_names = {symbol.name for symbol in cli_symbols}
    if project_path and not (root_matches or module_match or executable in _project_bins(repo)):
        # A checkout script (``script/run-tests groups``) is not one of the indexed CLIs, so the
        # indexed subcommand names say nothing about its positional arguments.
        command_names = set()
    flag_names = {
        name for symbol in index.by_kind.get(SymbolKind.cli_flag, []) for name in (symbol.name, *symbol.aliases)
    }
    arguments = index.by_kind.get(SymbolKind.cli_argument, [])
    root_positional = any(".root." in f".{symbol.qualified_name}." for symbol in arguments)
    passthrough = frozenset(
        parts[-2]
        for symbol in arguments
        if symbol.nargs == "..." and len(parts := symbol.qualified_name.split(".")) > 1
    )
    nullary = frozenset(
        name
        for symbol in index.by_kind.get(SymbolKind.cli_flag, [])
        if (symbol.default or "").casefold() in {"true", "false"}
        for name in (symbol.name, *symbol.aliases)
    )
    unknown = _unknown_tokens(
        tokens[executable_index + 1 :],
        command_names,
        flag_names,
        root_positional=root_positional,
        passthrough=passthrough,
        nullary=nullary,
    )
    if unknown and _shows_error(claim, context):
        return _unverifiable(
            claim,
            base_evidence,
            "The example's own output is an error message: it demonstrates a rejected command on purpose.",
        )
    if not unknown:
        return Finding(
            claim=claim,
            matched_symbol=root_matches[0] if root_matches else None,
            verdict=Verdict.ok,
            evidence=[
                *base_evidence,
                *[Evidence(file=item.file, line=item.line, text=item.name) for item in root_matches[:1]],
            ],
            confidence=0.75,
            reasons=["The project command and documented CLI tokens are statically consistent."],
        )
    plugin = next((p for token, _ in unknown if (p := context.installed_plugin(claim, token))), None)
    if plugin:
        return _unverifiable(claim, base_evidence, f"The command uses {plugin}, installed earlier in this document.")
    names = [token for token, _ in unknown]
    # Some indexers record subcommands without parent links, so several commands also mean a group.
    grouped = len(cli_symbols) > 1 or any(symbol.parent_id is not None for symbol in cli_symbols)
    graded = [_strength(token, resolved, command_names, flag_names, grouped=grouped) for token, resolved in unknown]
    strong = any(item[0] for item in graded)
    suggestion = next((item[1] for item in graded if item[1]), None)
    offset = claim.value.find(names[0])
    reason = f"Project command contains unknown command or flag: {', '.join(names)}."
    if suggestion:
        # Keep option names out of the reason text: rule fixes read the unknown flag from it.
        reason += " A similar indexed name exists; see the suggestion."
    elif not strong:
        reason += (
            " No similar name is indexed and no subcommand scope was resolved, so this may be a positional "
            "argument or an option the framework adds implicitly."
        )
    return Finding(
        claim=claim,
        verdict=Verdict.invalid_command,
        suggestion=suggestion,
        evidence=[
            *base_evidence,
            Evidence(
                file=claim.doc_path,
                line=claim.line,
                text=f"{claim.value}\n{' ' * max(0, offset)}^",
            ),
        ],
        confidence=STRONG_INVALID if strong else WEAK_INVALID,
        reasons=[reason],
    )


def validate_commands(
    claims: list[Claim], index: CodeIndex, repo: Path, context: MatchContext | None = None
) -> list[Finding]:
    selected = [claim for claim in claims if claim.kind.value == "code_command"]
    if not selected:
        return []
    context = context or MatchContext(repo.resolve(), index)
    bins = _project_bins(repo)
    return [validate_command(claim, index, repo, context, bins) for claim in selected]
